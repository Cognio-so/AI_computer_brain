from __future__ import annotations

import asyncio
import re
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Any

from sqlalchemy import event, text
from sqlalchemy.ext.asyncio import (
    AsyncEngine,
    AsyncSession,
    async_sessionmaker,
    create_async_engine,
)

AUTOINCREMENT_RE = re.compile(r"INTEGER PRIMARY KEY AUTOINCREMENT", re.IGNORECASE)
DATETIME_RE = re.compile(r"\bDATETIME\b", re.IGNORECASE)


def normalize_url(url: str) -> str:
    if url.startswith("sqlite:///"):
        return "sqlite+aiosqlite:///" + url[len("sqlite:///") :]
    if url.startswith("postgres://"):
        return "postgresql+asyncpg://" + url[len("postgres://") :]
    if url.startswith("postgresql://"):
        return "postgresql+asyncpg://" + url[len("postgresql://") :]
    return url


def translate_statement(statement: str, dialect: str) -> str:
    if dialect != "postgresql":
        return statement
    statement = AUTOINCREMENT_RE.sub(
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", statement
    )
    return DATETIME_RE.sub("TIMESTAMP", statement)


def load_statements(sql_dir: Path) -> list[str]:
    statements: list[str] = []
    for path in sorted(sql_dir.glob("*.sql")):
        for chunk in path.read_text(encoding="utf-8").split(";"):
            cleaned = chunk.strip()
            if cleaned:
                statements.append(cleaned)
    return statements


COLUMN_UPGRADES = (("api_keys", "secret_sealed", "TEXT"),)


class Database:
    def __init__(self, url: str, sql_dir: Path) -> None:
        self.url = normalize_url(url)
        self.sql_dir = sql_dir
        self.is_sqlite = self.url.startswith("sqlite")
        kwargs: dict[str, object] = {"pool_pre_ping": not self.is_sqlite}
        if self.is_sqlite:
            kwargs["connect_args"] = {"timeout": 30}
        self.engine: AsyncEngine = create_async_engine(self.url, **kwargs)
        if self.is_sqlite:
            event.listen(self.engine.sync_engine, "connect", _apply_sqlite_pragmas)
        self._sessions = async_sessionmaker(
            self.engine, expire_on_commit=False, class_=AsyncSession
        )

    @property
    def dialect(self) -> str:
        return self.engine.dialect.name

    def session(self) -> AsyncSession:
        return self._sessions()

    @asynccontextmanager
    async def transaction(self) -> AsyncIterator[AsyncSession]:
        session = self._sessions()
        try:
            yield session
        except BaseException:
            await asyncio.shield(_finish(session, commit=False))
            raise
        else:
            await asyncio.shield(_finish(session, commit=True))

    async def init(self) -> None:
        statements = load_statements(self.sql_dir)
        async with self.engine.begin() as connection:
            for statement in statements:
                await connection.execute(text(translate_statement(statement, self.dialect)))
            for table, column, ddl in COLUMN_UPGRADES:
                if not await self._has_column(connection, table, column):
                    await connection.execute(text(f"ALTER TABLE {table} ADD COLUMN {column} {ddl}"))

    async def _has_column(self, connection: Any, table: str, column: str) -> bool:
        if self.dialect.startswith("sqlite"):
            rows = (await connection.execute(text(f"PRAGMA table_info({table})"))).fetchall()
            return any(row[1] == column for row in rows)
        rows = (
            await connection.execute(
                text(
                    "SELECT column_name FROM information_schema.columns WHERE table_name = :table"
                ),
                {"table": table},
            )
        ).fetchall()
        return any(row[0] == column for row in rows)

    async def ping(self) -> bool:
        try:
            async with self.engine.connect() as connection:
                await connection.execute(text("SELECT 1"))
            return True
        except Exception:
            return False

    async def close(self) -> None:
        await self.engine.dispose()


async def _finish(session: AsyncSession, commit: bool) -> None:
    try:
        if commit:
            await session.commit()
        else:
            await session.rollback()
    finally:
        await session.close()


def _apply_sqlite_pragmas(dbapi_connection: object, _record: object) -> None:
    cursor = dbapi_connection.cursor()  # type: ignore[attr-defined]
    cursor.execute("PRAGMA foreign_keys=ON")
    cursor.execute("PRAGMA journal_mode=WAL")
    cursor.execute("PRAGMA busy_timeout=30000")
    cursor.close()
